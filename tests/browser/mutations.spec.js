for (const color of ['라이트', '다크']) for (const width of [390, 1440]) {
  test(`B ${color} ${width}px 200% text: modal, keyboard, theme preservation and success`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 1000 })
    await start(page)
    await setTheme(page, color)
    await page.addStyleTag({ content: 'html { font-size: 200% !important; }' })
    await page.getByRole('button', { name: '제안 수정 요청', exact: true }).click()
    const dialog = editor(page)
    await dialog.getByLabel('수정 방식').selectOption('facts')
    await dialog.getByLabel('인터넷 사용', { exact: true }).selectOption('UNKNOWN')
    await dialog.getByLabel('수정 사유 (필수)').fill('모바일과 테마 변경 후에도 입력 보존')
    await setTheme(page, color === '라이트' ? '다크' : '라이트', dialog)
    await expect(dialog.getByLabel('수정 사유 (필수)')).toHaveValue('모바일과 테마 변경 후에도 입력 보존')
    await setTheme(page, color, dialog)
    // Escape from nested theme dialog must return to the editor, not close it.
    await dialog.getByRole('button', { name: /화면 테마/ }).click()
    await page.keyboard.press('Escape')
    await expect(dialog).toBeVisible()
    await dialog.getByRole('button', { name: '데모 수정 요청', exact: true }).focus()
    await page.keyboard.press('Tab')
    await expect(dialog.getByRole('button', { name: /화면 테마/ })).toBeFocused()
    await page.keyboard.press('Shift+Tab')
    await expect(dialog.getByRole('button', { name: '데모 수정 요청', exact: true })).toBeFocused()
    expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await dialog.getByLabel('테이블 수', { exact: true }).scrollIntoViewIfNeeded()
    await page.screenshot({ path: testInfo.outputPath('facts-editor.png') })
    await dialog.getByRole('button', { name: '데모 수정 요청', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await page.locator('.proposal-preview').scrollIntoViewIfNeeded()
    await expect(page.locator('.proposal-preview')).toContainText('직원 검토 대기')
    await page.screenshot({ path: testInfo.outputPath('proposal-revised.png') })
    if (width === 390) {
      await page.getByRole('button', { name: '← 전체 매장 목록으로' }).click()
      await expect(page.locator('.entity-row').first()).toBeFocused()
    }
  })
}
