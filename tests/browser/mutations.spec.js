import { test, expect } from '@playwright/test'
import { makeFixture } from '../../src/services/fixtures.js'

async function start(page, name = '온기 식탁') {
  await page.goto('/')
  await page.getByRole('button', { name: '데모 매장 찾기', exact: true }).click()
  await expect(page.locator('.entity-row')).toHaveCount(3)
  await page.locator('.entity-row', { hasText: name }).click()
}
const editor = page => page.getByRole('dialog', { name: /매장 사실 보완|제안 수정 요청/, exact: true })
async function scenario(page, value) {
  const dialog = editor(page)
  await dialog.getByText('데모 검증 설정', { exact: true }).click()
  await dialog.getByLabel('변경 응답 시나리오').selectOption(value)
}
async function setTheme(page, name, scope = page) {
  await scope.getByRole('button', { name: /화면 테마/ }).click()
  await page.getByRole('radio', { name: new RegExp(name) }).check()
  await page.getByRole('button', { name: '적용 완료' }).click()
}
test('standalone facts merge, empty validation, cancellation and exact target isolation', async ({ page }) => {
  const external = [], errors = []
  page.on('request', r => { if (!r.url().startsWith('http://127.0.0.1:5173')) external.push(r.url()) })
  page.on('pageerror', e => errors.push(e.message))
  await start(page, '모퉁이 부엌')
  await page.getByRole('button', { name: '매장 사실 보완', exact: true }).click()
  let dialog = editor(page)
  await dialog.getByLabel('테이블 수 입력 방식').selectOption('value')
  await expect(dialog.getByText('테이블 수 값을 확인해 주세요.')).toBeVisible()
  await expect(dialog.getByRole('button', { name: '데모 사실 반영' })).toBeDisabled()
  await dialog.getByLabel('테이블 수', { exact: true }).fill('0')
  await dialog.getByLabel('인터넷 사용', { exact: true }).selectOption('false')
  await expect(dialog.getByRole('region', { name: '변경 전후 비교' })).toContainText('미확인 → 없음')
  await dialog.getByRole('button', { name: '취소', exact: true }).click()
  await expect(page.getByRole('button', { name: '매장 사실 보완', exact: true })).toBeFocused()
  await expect(page.locator('.evidence-item')).toHaveCount(2)
  await page.getByRole('button', { name: '매장 사실 보완', exact: true }).click()
  dialog = editor(page)
  await expect(dialog.getByLabel('인터넷 사용', { exact: true })).toHaveValue('UNKNOWN')
  await dialog.getByLabel('테이블 수 입력 방식').selectOption('value')
  await dialog.getByLabel('테이블 수', { exact: true }).fill('0.5')
  await dialog.getByLabel('인터넷 사용', { exact: true }).selectOption('false')
  await dialog.getByRole('button', { name: '데모 사실 반영' }).dblclick()
  await expect(dialog).toHaveCount(0)
  await expect(page.locator('.facts-grid')).toContainText('0.5')
  await expect(page.locator('.evidence-item')).toHaveCount(4)
  await expect(page.locator('.evidence-item', { hasText: '직원 확인' })).toHaveCount(2)
  await expect(page.locator('.detail-heading')).toContainText('확인 필요')
  await expect(page.locator('.evidence-content')).toContainText(['모퉁이 부엌', '모퉁이 분식', '0.5', '없음'])
  await page.locator('.entity-row', { hasText: '소담한' }).click()
  await expect(page.locator('.facts-grid > div', { hasText: '인터넷 사용' })).toContainText('미확인')
  expect(external).toEqual([]); expect(errors).toEqual([])
})
